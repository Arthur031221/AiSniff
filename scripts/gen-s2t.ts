// Builds src/engine/s2t-table.ts from the OpenCC STCharacters dictionary (Apache-2.0, see THIRD_PARTY_NOTICES.md).
// Only one-to-one UTF-16 mappings are kept so offsets in the converted copy match the original text.
import { writeFileSync } from "node:fs";
// @ts-ignore the dictionary ships without types
import st from "../node_modules/opencc-js/dist/esm-lib/dict/STCharacters.js";

const pairs: string[] = [];
for (const entry of (st as string).split("|")) {
  const [simplified, ...traditional] = entry.split(" ");
  const target = traditional[0];
  if (!simplified || !target) continue;
  if (simplified.length !== 1 || target.length !== 1 || simplified === target) continue;
  pairs.push(simplified + target);
}
const out = `// Generated by scripts/gen-s2t.ts. Do not edit.\nexport const S2T_PAIRS = ${JSON.stringify(pairs.join(""))};\n`;
writeFileSync("src/engine/s2t-table.ts", out);
console.log(`${pairs.length} character pairs`);
